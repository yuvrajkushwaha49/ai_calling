#!/usr/bin/env node
/**
 * generate-ai-context.cjs
 *
 * Scans the project directory and generates an up-to-date, readable file tree
 * in .ai/FILE_STRUCTURE.md.
 *
 * Uses only Node.js built-in modules. Safe to run repeatedly across Windows and Linux.
 */

const fs = require('fs');
const path = require('path');

const IGNORE_PATTERNS = new Set([
  'node_modules',
  '.git',
  '.next',
  'dist',
  'build',
  'coverage',
  '.cache',
  'tmp',
  'temp',
  '.turbo',
]);

function shouldIgnore(name) {
  return IGNORE_PATTERNS.has(name);
}

function buildTree(currentDir, relativePrefix = '', depth = 0, maxDepth = 6) {
  if (depth > maxDepth) {
    return `${relativePrefix}└── ... (max depth reached)\n`;
  }

  let entries = [];
  try {
    entries = fs.readdirSync(currentDir, { withFileTypes: true });
  } catch (err) {
    return `${relativePrefix}└── [Error reading directory: ${err.message}]\n`;
  }

  // Filter out ignored entries
  const filtered = entries.filter((entry) => !shouldIgnore(entry.name));

  // Sort: directories first, then alphabetical
  filtered.sort((a, b) => {
    if (a.isDirectory() && !b.isDirectory()) return -1;
    if (!a.isDirectory() && b.isDirectory()) return 1;
    return a.name.localeCompare(b.name, undefined, { sensitivity: 'base' });
  });

  let output = '';
  filtered.forEach((entry, index) => {
    const isLast = index === filtered.length - 1;
    const branch = isLast ? '└── ' : '├── ';
    const nextPrefix = relativePrefix + (isLast ? '    ' : '│   ');
    const fullPath = path.join(currentDir, entry.name);

    if (entry.isDirectory()) {
      output += `${relativePrefix}${branch}${entry.name}/\n`;
      output += buildTree(fullPath, nextPrefix, depth + 1, maxDepth);
    } else {
      output += `${relativePrefix}${branch}${entry.name}\n`;
    }
  });

  return output;
}

function generate() {
  const rootDir = path.resolve(__dirname, '..');
  const aiDir = path.join(rootDir, '.ai');
  const outputFile = path.join(aiDir, 'FILE_STRUCTURE.md');

  if (!fs.existsSync(aiDir)) {
    fs.mkdirSync(aiDir, { recursive: true });
  }

  const generatedTime = new Date().toISOString();
  const tree = buildTree(rootDir, '', 0, 8);

  const content = `# Project File Structure

> **Notice:** This document is automatically generated by \`scripts/generate-ai-context.cjs\` via \`npm run ai:context\`.
> Do not edit this file manually. To regenerate, execute \`npm run ai:context\` from the workspace root.
> Last generated: ${generatedTime}

\`\`\`
${path.basename(rootDir)}/
${tree}\`\`\`
`;

  fs.writeFileSync(outputFile, content, 'utf8');
  console.log('✓ Successfully generated .ai/FILE_STRUCTURE.md');
}

generate();