#!/usr/bin/env bash
# ==============================================================================
# Workains Reality CRM — Safe Zero-Downtime Atomic Deployment Script (Round 8.3)
# Guarantees build success & entrypoint validation BEFORE restarting PM2.
# Automatically rolls back to previous working release if build or health check fails.
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
BACKEND_DIR="${ROOT_DIR}/backend"

echo "========================================================"
echo "🚀 WORKAINS REALITY CRM — SAFE DEPLOYMENT SEQUENCE (8.3)"
echo "========================================================"
echo "📂 Root Directory:    ${ROOT_DIR}"
echo "📂 Backend Directory: ${BACKEND_DIR}"

cd "${ROOT_DIR}"

# 1. Pull latest code from main
echo "📥 [1/6] Pulling latest code from origin main..."
git pull origin main

# 2. Preserve existing working build artifact
echo "🛡️ [2/6] Preserving working build backup..."
if [ -d "${BACKEND_DIR}/dist" ] && [ -f "${BACKEND_DIR}/dist/main.js" ]; then
  rm -rf "${BACKEND_DIR}/dist.bak"
  cp -r "${BACKEND_DIR}/dist" "${BACKEND_DIR}/dist.bak"
  echo "✅ Backed up current working dist to dist.bak"
fi

# 3. Generate Prisma client & build backend
echo "🔨 [3/6] Building backend with NestJS compiler..."
cd "${BACKEND_DIR}"
npx prisma generate

if ! npm run build; then
  echo "❌ [ERROR] Build failed! Aborting deployment without restarting PM2."
  if [ -d "${BACKEND_DIR}/dist.bak" ]; then
    rm -rf "${BACKEND_DIR}/dist"
    cp -r "${BACKEND_DIR}/dist.bak" "${BACKEND_DIR}/dist"
    echo "↩️ Restored working dist from dist.bak"
  fi
  exit 1
fi

# 4. Pre-deployment artifact validation
echo "🔍 [4/6] Validating compiled build artifacts..."
if [ ! -f "${BACKEND_DIR}/dist/main.js" ]; then
  echo "❌ [FATAL] dist/main.js was not generated by the build! Rolling back."
  if [ -d "${BACKEND_DIR}/dist.bak" ]; then
    cp -r "${BACKEND_DIR}/dist.bak" "${BACKEND_DIR}/dist"
  fi
  exit 1
fi

ENTRY_SIZE=$(wc -c < "${BACKEND_DIR}/dist/main.js")
if [ "${ENTRY_SIZE}" -lt 500 ]; then
  echo "❌ [FATAL] dist/main.js is corrupt or empty (${ENTRY_SIZE} bytes)! Rolling back."
  if [ -d "${BACKEND_DIR}/dist.bak" ]; then
    cp -r "${BACKEND_DIR}/dist.bak" "${BACKEND_DIR}/dist"
  fi
  exit 1
fi

node -c "${BACKEND_DIR}/dist/main.js"
echo "✅ Artifact verified: dist/main.js syntax valid (${ENTRY_SIZE} bytes)"

# 5. Zero-downtime PM2 reload
echo "🔄 [5/6] Reloading PM2 crm-backend with ecosystem config..."
cd "${ROOT_DIR}"
if pm2 describe crm-backend > /dev/null 2>&1; then
  pm2 reload ecosystem.config.js --only crm-backend --update-env
else
  pm2 start ecosystem.config.js --only crm-backend
fi

# 6. Post-deployment health verification
echo "🩺 [6/6] Verifying health and version telemetry on http://localhost:4000/api/version..."
sleep 2

HEALTH_SUCCESS=false
for i in {1..10}; do
  if RESPONSE=$(curl -s -f http://localhost:4000/api/version 2>/dev/null); then
    echo "✅ Health check PASSED on attempt ${i}!"
    echo "📊 Telemetry: ${RESPONSE}"
    HEALTH_SUCCESS=true
    break
  fi
  echo "⏳ Waiting for backend to bind socket (attempt ${i}/10)..."
  sleep 1
done

if [ "${HEALTH_SUCCESS}" = false ]; then
  echo "❌ [ALERT] Post-deployment health check failed! Rolling back to dist.bak..."
  if [ -d "${BACKEND_DIR}/dist.bak" ]; then
    cp -r "${BACKEND_DIR}/dist.bak" "${BACKEND_DIR}/dist"
    pm2 reload ecosystem.config.js --only crm-backend --update-env
  fi
  exit 1
fi

echo "========================================================"
echo "🎉 DEPLOYMENT SUCCESSFUL — RUNNING ROUND 8.3 IN PRODUCTION"
echo "========================================================"

